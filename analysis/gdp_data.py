YEARS = list(range(2000, 2024))
BASE_YEAR = 2019


def build_index_series() -> pd.DataFrame:
    """
    Convert absolute PPP levels to an index normalised to BASE_YEAR = 100.
    Only years present in ALL series are kept (complete-case panel).
    """
    # Build a unified DataFrame from the raw dicts
    records = []
    for iso, year_vals in RAW_DATA.items():
        for yr, val in year_vals.items():
            records.append({"year": yr, "iso": iso, "gdp_pc": val})

    df = pd.DataFrame(records)
    wide = df.pivot(index="year", columns="iso", values="gdp_pc").sort_index()

    # Drop columns with any missing value (complete-case donor pool)
    wide = wide.dropna(axis=1)

    # Normalise to BASE_YEAR = 100
    wide = wide.div(wide.loc[BASE_YEAR]) * 100

    # Restrict to study window 2000–2023
    wide = wide.loc[2000:2023]
    wide.index.name = "year"
    return wide


