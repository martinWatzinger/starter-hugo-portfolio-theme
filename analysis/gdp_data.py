YEARS = list(range(2000, 2024))  # 2000–2023


def build_index_series() -> pd.DataFrame:
    """
    Convert growth-rate arrays to index series, normalised to 2019 = 100.
    Returns a DataFrame with years as index and ISO3 codes as columns.
    """
    data = {}
    base_year = 2019
    base_pos  = YEARS.index(base_year)  # position of 2019 in YEARS

    for iso, rates in GROWTH_RATES.items():
        assert len(rates) == 23, f"{iso}: expected 23 rates, got {len(rates)}"
        # Build level series starting from index=1 at year 2000
        levels = np.ones(len(YEARS))
        for i, g in enumerate(rates):
            levels[i + 1] = levels[i] * (1 + g / 100)
        # Normalise so that 2019 = 100
        levels = levels / levels[base_pos] * 100
        data[iso] = levels

    df = pd.DataFrame(data, index=YEARS)
    df.index.name = "year"
    return df


